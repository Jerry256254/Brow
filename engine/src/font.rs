use std::sync::OnceLock;

static FONT: OnceLock<[[u8; 8]; 95]> = OnceLock::new();

fn font() -> &'static [[u8; 8]; 95] {
    FONT.get_or_init(|| {
        let mut out = [[0u8; 8]; 95];
        for (i, art) in GLYPHS_ART.iter().enumerate() {
            let chars: Vec<char> = art.chars().collect();
            debug_assert_eq!(chars.len(), 35, "glyph {} has {} chars", 32 + i, chars.len());
            for row in 0..7usize {
                let mut bits = 0u8;
                for col in 0..5usize {
                    if chars[row * 5 + col] == '#' {
                        bits |= 1 << col;
                    }
                }
                out[i][row] = bits;
            }
        }
        out
    })
}

/// Bitmap of a character (8 rows, bit 0 = leftmost of 5 used columns). Unknown -> '?'.
pub fn glyph(c: char) -> [u8; 8] {
    let f = font();
    let idx = if (32..=126).contains(&(c as u32)) {
        (c as usize) - 32
    } else if c == '\u{00a0}' {
        0
    } else {
        ('?' as usize) - 32
    };
    f[idx]
}

/// Integer paint scale for a font size in px (16px -> 1, 32px -> 2, ...).
pub fn scale_for(font_size: f32) -> u32 {
    ((font_size / 16.0).round() as i32).clamp(1, 4) as u32
}

pub fn char_advance(c: char, scale: u32) -> f32 {
    (if c == ' ' { SPACE_ADVANCE } else { ADVANCE }) as f32 * scale as f32
}

pub fn text_width(text: &str, font_size: f32) -> f32 {
    let s = scale_for(font_size);
    text.chars().map(|c| char_advance(c, s)).sum()
}

pub fn line_height(font_size: f32) -> f32 {
    LINE_HEIGHT as f32 * scale_for(font_size) as f32
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_glyphs_are_35_chars() {
        for (i, g) in GLYPHS_ART.iter().enumerate() {
            assert_eq!(g.chars().count(), 35, "glyph {}", 32 + i);
        }
    }

    #[test]
    fn glyph_a_has_pixels() {
        let g = glyph('A');
        assert!(g.iter().any(|&r| r != 0));
        assert_eq!(glyph('A'), glyph('A'));
        assert_eq!(glyph('\u{20ac}'), glyph('?'));
    }

    #[test]
    fn metrics() {
        assert_eq!(scale_for(16.0), 1);
        assert_eq!(scale_for(32.0), 2);
        assert_eq!(scale_for(8.0), 1);
        assert!(text_width("hello", 16.0) > 0.0);
        assert!(text_width("a b", 16.0) > text_width("ab", 16.0));
    }
}
